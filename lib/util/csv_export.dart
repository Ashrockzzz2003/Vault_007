import 'dart:io';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:path_provider/path_provider.dart';
// import 'package:fluttertoast/fluttertoast.dart'; // Replaced with SnackBar
import 'toast_helper.dart';
import 'package:local_auth/local_auth.dart';
import 'package:vaultzerozeroseven_marktwo/db/database.dart';
import 'package:vaultzerozeroseven_marktwo/model/passwords.dart';
import 'package:vaultzerozeroseven_marktwo/util/crypto.dart';

class CsvExportService {
  final LocalAuthentication auth = LocalAuthentication();

  Future<bool> _authenticateForExport() async {
    bool authenticated = false;
    try {
      authenticated = await auth.authenticate(
        localizedReason: 'Please authenticate to export your passwords.',
        options: const AuthenticationOptions(
          useErrorDialogs: true,
          sensitiveTransaction: true,
        ),
      );
    } on PlatformException catch (e) {
      return false;
    }
    return authenticated;
  }

  String _escapeCSVField(String field) {
    if (field.contains(',') || field.contains('"') || field.contains('\n')) {
      return '"${field.replaceAll('"', '""')}"';
    }
    return field;
  }

  String _formatDateTime(DateTime? dateTime) {
    if (dateTime == null) return '';
    return '${dateTime.year}-${dateTime.month.toString().padLeft(2, '0')}-${dateTime.day.toString().padLeft(2, '0')} ${dateTime.hour.toString().padLeft(2, '0')}:${dateTime.minute.toString().padLeft(2, '0')}:${dateTime.second.toString().padLeft(2, '0')}';
  }

  Future<void> exportPasswordsToCSV(
      BuildContext context, IsarService isarService) async {
    // Authenticate before export
    bool authenticated = await _authenticateForExport();

    if (!authenticated) {
      ToastHelper.showToast(context, "Authentication failed. Export cancelled.");
      return;
    }

    try {
      // Get all passwords
      List<Passwords> passwords = await isarService.getPasswords();

      if (passwords.isEmpty) {
        ToastHelper.showToast(context, "No passwords to export.");
        return;
      }

      // Create CSV content
      StringBuffer csvContent = StringBuffer();

      // CSV Header
      csvContent.writeln(
          'Service Name,Username,Password,Created At,Updated At,Auto Generated,Hint,Tags');

      // CSV Rows
      for (var password in passwords) {
        String serviceName = _escapeCSVField(password.serviceName ?? '');
        String userName = _escapeCSVField(password.userName ?? '');
        String decryptedPassword = _escapeCSVField(
            Crypto().decryptMyData(password.password ?? ''));
        String createdAt = _escapeCSVField(_formatDateTime(password.createdAt));
        String updatedAt = _escapeCSVField(_formatDateTime(password.updatedAt));
        String isAutoGenerated = password.isAutoGenerated == true ? 'Yes' : 'No';
        String hint = '';
        if (password.hint != null && password.hint!.isNotEmpty) {
          hint = _escapeCSVField(Crypto().decryptMyData(password.hint!));
        }
        String tags = _escapeCSVField(password.tags.join('; '));

        csvContent.writeln(
            '$serviceName,$userName,$decryptedPassword,$createdAt,$updatedAt,$isAutoGenerated,$hint,$tags');
      }

      // Get directory to save file
      Directory? directory;
      if (Platform.isAndroid) {
        directory = await getExternalStorageDirectory();
      } else {
        directory = await getApplicationDocumentsDirectory();
      }

      if (directory == null) {
        throw Exception('Could not access storage directory');
      }

      // Create filename with timestamp
      String timestamp =
          DateTime.now().toString().replaceAll(RegExp(r'[:\s\.]'), '_');
      String fileName = 'vault007_passwords_$timestamp.csv';
      String filePath = '${directory.path}/$fileName';

      // Write to file
      File file = File(filePath);
      await file.writeAsString(csvContent.toString());

      // Show success message
      ToastHelper.showToast(context, "Passwords exported successfully!\nLocation: $filePath");

      // Show dialog with file location
      _showExportSuccessDialog(context, filePath);
    } catch (e) {
      ToastHelper.showToast(context, "Export failed: ${e.toString()}");
    }
  }

  void _showExportSuccessDialog(BuildContext context, String filePath) {
    showDialog(
      context: context,
      builder: (BuildContext context) {
        return AlertDialog(
          actionsAlignment: MainAxisAlignment.center,
          icon: const Icon(Icons.check_circle_outline_rounded),
          title: const Text('Export Successful'),
          content: Column(
            mainAxisSize: MainAxisSize.min,
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              const Text('Your passwords have been exported to:'),
              const SizedBox(height: 8),
              SelectableText(
                filePath,
                style: const TextStyle(fontSize: 12),
              ),
              const SizedBox(height: 16),
              const Text(
                'Warning: This file contains unencrypted passwords. Please store it securely.',
                style: TextStyle(
                  fontWeight: FontWeight.bold,
                  color: Colors.red,
                ),
              ),
            ],
          ),
          actions: <Widget>[
            FilledButton.tonal(
              child: const Text('OK'),
              onPressed: () {
                Navigator.of(context).pop();
              },
            ),
          ],
        );
      },
    );
  }
}
